/**
 * Builds dist/team-shell.js: the browser-script version of the header for static HTML pages.
 *
 *   npm run build:script   writes dist/team-shell.js
 *   npm run check:dist     rebuilds in memory and fails if the committed file is stale
 *
 * IIFE, minified, React + ReactDOM bundled, styles/team-shell.css minified and injected by
 * the script itself (no separate stylesheet). The output is committed: apps install this
 * package from git and copy the file as-is, without a build step.
 */
import { build, transform } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTFILE = join(ROOT, "dist", "team-shell.js");
const check = process.argv.includes("--check");

const pkg = JSON.parse(await readFile(join(ROOT, "package.json"), "utf8"));
const rawCss = await readFile(join(ROOT, "styles", "team-shell.css"), "utf8");
const { code: css } = await transform(rawCss, { loader: "css", minify: true });

const result = await build({
  absWorkingDir: ROOT,
  entryPoints: ["src/script/mount.tsx"],
  outfile: OUTFILE,
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  jsx: "automatic",
  legalComments: "eof",
  charset: "utf8",
  write: false,
  logLevel: "warning",
  define: {
    "process.env.NODE_ENV": '"production"',
    // No NEXT_PUBLIC_* env in a static page: nav URLs fall back to their defaults.
    "process.env": "{}",
    __TEAM_SHELL_CSS__: JSON.stringify(css.trim()),
  },
  banner: {
    js: `/*! @team/shell v${pkg.version} — generated by \`npm run build:script\` from src/script/mount.tsx; do not edit. */`,
  },
});

const built = result.outputFiles[0].text;

if (check) {
  const current = await readFile(OUTFILE, "utf8").catch(() => null);
  if (current !== built) {
    console.error(
      current === null
        ? "dist/team-shell.js is missing. Run `npm run build:script` and commit it."
        : "dist/team-shell.js is stale. Run `npm run build:script` and commit it."
    );
    process.exit(1);
  }
  console.log(`dist/team-shell.js is up to date (${built.length} bytes).`);
} else {
  await mkdir(dirname(OUTFILE), { recursive: true });
  await writeFile(OUTFILE, built);
  console.log(`Wrote dist/team-shell.js (${built.length} bytes).`);
}
